#!/usr/bin/env python3
"""Embed web/config.html into the firmware as a gzipped byte array.

Writes tiger_timer/config_html.h. Run this after every edit to web/config.html, before
compiling - the Remote Config page is served from firmware, not from LittleFS, so a firmware
update also updates the page while the trivia files on LittleFS are left untouched.
"""
import gzip, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "web" / "config.html"
dst = root / "tiger_timer" / "config_html.h"

data = gzip.compress(src.read_bytes(), compresslevel=9, mtime=0)  # mtime=0: same input -> same bytes
lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
dst.write_text(
    "// GENERATED by tools/embed_config_html.py from web/config.html - do not edit by hand.\n"
    "// The Remote Config page, gzip-compressed; served with Content-Encoding: gzip.\n"
    "#pragma once\n#include <Arduino.h>\n\n"
    f"const size_t CONFIG_HTML_GZ_LEN = {len(data)};\n"
    "const uint8_t CONFIG_HTML_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n"
)
print(f"{src.name}: {src.stat().st_size} bytes -> {len(data)} gzipped -> {dst.relative_to(root)}")
